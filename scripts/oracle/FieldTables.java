// Generates src/mpp/field-tables.js from MPXJ field definitions (MPP14 format).
// Usage: java -cp "<mpxj.jar>;<lib/*>" FieldTables.java <output.js>
// Used by FieldMap: fixed block size of every field and,
// for the fields the reader uses, indexes and data type.

import org.mpxj.DataType;
import org.mpxj.FieldType;
import org.mpxj.ProjectFile;
import org.mpxj.common.FieldTypeHelper;

import java.io.PrintWriter;
import org.mpxj.AssignmentField;
import org.mpxj.common.MPPAssignmentField;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

public class FieldTables
{
   // Local custom fields, in the order the reader returns them (same order in Dump.java).
   private static final List<String> CUSTOM_FIELDS = new ArrayList<>();
   static
   {
      Map<String, Integer> counts = new LinkedHashMap<>();
      counts.put("TEXT", 30);
      counts.put("NUMBER", 20);
      counts.put("COST", 10);
      counts.put("DATE", 10);
      counts.put("START", 10);
      counts.put("FINISH", 10);
      counts.put("DURATION", 10);
      counts.put("FLAG", 20);
      counts.forEach((prefix, count) -> {
         for (int i = 1; i <= count; i++)
         {
            CUSTOM_FIELDS.add(prefix + i);
         }
      });
   }

   // Fixed-name enterprise fields (Project Server), in the order the reader returns them (as in Dump.java).
   private static final List<String> ENTERPRISE_FIELDS = new ArrayList<>();
   static
   {
      Map<String, Integer> counts = new LinkedHashMap<>();
      counts.put("TEXT", 40);
      counts.put("NUMBER", 40);
      counts.put("COST", 10);
      counts.put("DATE", 30);
      counts.put("DURATION", 10);
      counts.put("FLAG", 20);
      counts.forEach((prefix, count) -> {
         for (int i = 1; i <= count; i++)
         {
            ENTERPRISE_FIELDS.add("ENTERPRISE_" + prefix + i);
         }
      });
   }

   // Fields used by the reader, per class.
   private static final Map<String, Set<String>> WANTED = new LinkedHashMap<>();
   static
   {
      WANTED.put("task", Set.of("ID", "UNIQUE_ID", "NAME", "OUTLINE_LEVEL", "WBS", "DURATION", "DURATION_UNITS", "START", "FINISH",
         "PERCENT_COMPLETE", "PARENT_TASK_UNIQUE_ID", "SCHEDULED_START", "SCHEDULED_FINISH", "SCHEDULED_DURATION",
         "MANUAL_DURATION", "MANUAL_DURATION_UNITS", "ACTUAL_DURATION_UNITS", "CONSTRAINT_TYPE", "LATE_START", "LATE_FINISH",
         "ACTUAL_START", "ACTUAL_FINISH", "CREATED", "TASK_MODE", "SUBPROJECT_TASK_ID", "SUBPROJECT_TASK_UNIQUE_ID", "MILESTONE", "SUMMARY",
         "RECURRING_DATA", "BASELINE_DURATION_UNITS", "BASELINE_ESTIMATED_DURATION", "WORK", "REMAINING_WORK"));
      WANTED.put("resource", Set.of("ID", "UNIQUE_ID", "NAME", "TYPE", "INITIALS", "GROUP", "MAX_UNITS", "STANDARD_RATE",
         "STANDARD_RATE_UNITS", "COST_RATE_A", "AVAILABILITY_DATA", "AVAILABLE_FROM", "AVAILABLE_TO"));
      WANTED.put("assignment", Set.of("UNIQUE_ID", "TASK_UNIQUE_ID", "RESOURCE_UNIQUE_ID", "ASSIGNMENT_UNITS", "WORK",
         "START", "FINISH"));
      WANTED.put("relation", Set.of("UNIQUE_ID", "TASK1", "TASK2", "TYPE", "LAG", "LAG_UNITS"));
      for (String cls : List.of("task", "resource", "assignment"))
      {
         Set<String> fields = new LinkedHashSet<>(WANTED.get(cls));
         fields.addAll(CUSTOM_FIELDS);
         fields.addAll(ENTERPRISE_FIELDS);
         for (int i = 1; i <= 10; i++)
         {
            fields.add("DURATION" + i + "_UNITS");
            fields.add("ENTERPRISE_DURATION" + i + "_UNITS");
         }
         WANTED.put(cls, fields);
      }
   }

   private static final Map<String, int[]> CLASSES = new LinkedHashMap<>();
   static
   {
      CLASSES.put("task", new int[] { 0x0B400000, 1414 });
      CLASSES.put("resource", new int[] { 0x0C400000, 863 });
      CLASSES.put("assignment", new int[] { 0x0F400000, 717 });
      CLASSES.put("relation", new int[] { 0x0D400000, 10 });
   }

   public static void main(String[] args) throws Exception
   {
      ProjectFile file = new ProjectFile();
      file.getProjectProperties().setMppFileType(Integer.valueOf(14));

      try (PrintWriter pw = new PrintWriter(args[0], "UTF-8"))
      {
         pw.println("// GENERATED by scripts/oracle/FieldTables.java (data from MPXJ, LGPL-2.1). Do not edit by hand.");
         pw.println("// FIELD_SIZES: one char per field index = bytes used in the fixed block (g = 16).");
         pw.println("// FIELDS: for the fields we use, matching MPP14 indexes and data type.");

         StringBuilder sizes = new StringBuilder("export const FIELD_SIZES = {\n");
         StringBuilder fields = new StringBuilder("export const FIELDS = {\n");

         for (Map.Entry<String, int[]> entry : CLASSES.entrySet())
         {
            String name = entry.getKey();
            int base = entry.getValue()[0];
            int max = entry.getValue()[1];
            StringBuilder s = new StringBuilder();
            Map<String, List<Integer>> indexes = new LinkedHashMap<>();
            Map<String, String> types = new LinkedHashMap<>();

            for (int index = 0; index < max; index++)
            {
               FieldType type = FieldTypeHelper.getInstance(file, base | index);
               s.append(sizeCode(type == null ? null : type.getDataType()));
               if (type != null && type.getFieldTypeClass() != null && WANTED.get(name).contains(type.name()))
               {
                  indexes.computeIfAbsent(type.name(), k -> new ArrayList<>()).add(Integer.valueOf(index));
                  types.put(type.name(), type.getDataType() == null ? null : type.getDataType().name());
               }
            }

            sizes.append("  ").append(name).append(": '").append(s.toString().replaceAll("0+$", "")).append("',\n");
            fields.append("  ").append(name).append(": {\n");
            for (String field : indexes.keySet())
            {
               fields.append("    ").append(field).append(": { indexes: ").append(indexes.get(field)).append(", type: '").append(types.get(field)).append("' },\n");
            }
            fields.append("  },\n");
         }

         pw.print(sizes.append("};\n\n"));
         pw.print(fields.append("};\n\n"));

         // Local custom fields in order; for assignments, fallback keys in var data
         // (MPP14Reader.ALTERNATE_VAR_DATA: 0x4000 + position in MPPAssignmentField).
         pw.println("// CUSTOM_FIELDS: local custom fields, in the order the reader returns them.");
         printList(pw, "CUSTOM_FIELDS", CUSTOM_FIELDS);
         pw.println("// ENTERPRISE_FIELDS: fixed-name enterprise fields, in the order the reader returns them.");
         printList(pw, "ENTERPRISE_FIELDS", ENTERPRISE_FIELDS);
         pw.println("// ASSIGNMENT_ALTERNATE_KEYS: fallback keys in assignment var data.");
         pw.println("export const ASSIGNMENT_ALTERNATE_KEYS = {");
         AssignmentField[] alternate = MPPAssignmentField.getAlternateFieldArray();
         for (int i = 0; i < alternate.length; i++)
         {
            if (alternate[i] != null)
            {
               pw.println("  " + alternate[i].name() + ": 0x" + Integer.toHexString(0x4000 + i) + ",");
            }
         }
         pw.println("};");
      }
   }

   private static void printList(PrintWriter pw, String name, List<String> values)
   {
      pw.print("export const " + name + " = [");
      for (int i = 0; i < values.size(); i++)
      {
         pw.print((i % 8 == 0 ? "\n  " : " ") + "'" + values.get(i) + "',");
      }
      pw.println("\n];\n");
   }

   // Same sizes as FieldMap.getFixedDataFieldSize.
   private static char sizeCode(DataType dataType)
   {
      if (dataType == null)
      {
         return '0';
      }
      switch (dataType)
      {
         case DATE:
         case INTEGER:
         case DURATION:
            return '4';
         case TIME_UNITS:
         case CONSTRAINT:
         case PRIORITY:
         case PERCENTAGE:
         case TASK_TYPE:
         case ACCRUE:
         case SHORT:
         case BOOLEAN:
         case DELAY:
         case WORKGROUP:
         case RATE_UNITS:
         case EARNED_VALUE_METHOD:
         case RESOURCE_REQUEST_TYPE:
            return '2';
         case CURRENCY:
         case UNITS:
         case RATE:
         case WORK:
            return '8';
         case WORK_UNITS:
            return '1';
         case GUID:
            return 'g';
         default:
            return '0';
      }
   }
}
